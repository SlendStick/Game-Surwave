def build():
    perks = []          # плоский список
    trees = []          # структура дерева
    ids = set()
    for tid, tname, nodes in TREES:
        tree = {"id": tid, "name": tname, "nodes": []}
        t1 = f"{tid}_{nodes[0][0]}"
        for (suffix, name, tier, branch, desc, mods, flags) in nodes:
            pid = f"{tid}_{suffix}"
            assert pid not in ids, pid
            ids.add(pid)
            req = []
            if tier == 2:
                req = [t1]
            elif tier == 3:
                req = []
            perk = {
                "id": pid, "name": name, "tree": tid, "tier": tier,
                "branch": branch, "desc": desc,
                "mods": mods, "flags": flags,
                "req": req,
                "req_any": [f"{tid}_{nodes[1][0]}", f"{tid}_{nodes[2][0]}"] if tier == 3 else [],
                "max_stacks": 1,
            }
            perks.append(perk)
            tree["nodes"].append(pid)
        trees.append(tree)
    return {"trees": trees, "perks": perks}

if __name__ == "__main__":
    data = build()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "data", "perks.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print("perks:", len(data["perks"]), "trees:", len(data["trees"]))
